export interface MindNode {
  id: string;
  label: string;
  kind: "root" | "pillar" | "concept" | "language" | "framework" | "practice";
  color?: string;
  summary: string;
  why?: string;
  path?: string[]; // learning steps
  link?: string; // internal link
  children?: MindNode[];
}

const concept = (id: string, label: string, summary: string, why: string, path: string[]): MindNode => ({
  id: `concept-${id}`,
  label,
  kind: "concept",
  summary,
  why,
  path,
  link: `/rosetta?concept=${id}`,
});

const fw = (id: string, label: string, summary: string, why: string, path: string[]): MindNode => ({
  id: `fw-${id}`,
  label,
  kind: "framework",
  summary,
  why,
  path,
});

